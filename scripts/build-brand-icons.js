// Generate public/js/brand-icons.js from the simple-icons package (CC0-1.0).
// Run after upgrading simple-icons:  npm run icons
// The marks are the networks' trademarks: show them unaltered, only to identify the network.
import { readFileSync, writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

const WANTED = {
  instagram: si.siInstagram,
  facebook: si.siFacebook,
  youtube: si.siYoutube,
  x: si.siX,
  threads: si.siThreads,
  tiktok: si.siTiktok,
  pinterest: si.siPinterest,
  whatsapp: si.siWhatsapp,
};

const out = Object.fromEntries(Object.entries(WANTED).map(([key, icon]) => {
  if (!icon) throw new Error(`simple-icons has no icon for ${key}`);
  return [key, { title: icon.title, hex: `#${icon.hex}`, path: icon.path }];
}));

// The package doesn't export its package.json, so read the version from disk.
const { version } = JSON.parse(readFileSync('node_modules/simple-icons/package.json', 'utf8'));
writeFileSync('public/js/brand-icons.js', `// Generated by scripts/build-brand-icons.js from simple-icons ${version} (CC0-1.0). Do not edit.
// These are the networks' trademarks, shown unaltered to identify each network.
// LinkedIn is not included (removed from simple-icons at LinkedIn's request); the app uses a text badge.
export const BRAND_ICONS = ${JSON.stringify(out, null, 1)};
`);
console.log(`Wrote ${Object.keys(out).length} icons from simple-icons ${version}`);
